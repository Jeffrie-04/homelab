#!/usr/bin/env bash
# Generate fresh credentials for Immich + Nextcloud and write them as
# SealedSecrets into the repo. Run from the repo root on a machine with
# kubectl + kubeseal pointed at the cluster.
#
# Plaintext values go to ~/.homelab-rotation.env (chmod 600, outside the
# repo) so the DB steps in docs/SECRET-ROTATION.md can use them.
# Delete that file when rotation is done.
set -euo pipefail

# Change these if your controller isn't the kubeseal default.
SS_NAME="${SS_NAME:-sealed-secrets-controller}"
SS_NS="${SS_NS:-kube-system}"

ENV_FILE="$HOME/.homelab-rotation.env"
[ -f apps/argocd-apps/immich-app.yaml ] || { echo "Run from the repo root"; exit 1; }
command -v kubeseal >/dev/null || { echo "kubeseal not found (brew install kubeseal)"; exit 1; }

# 32 alphanumeric chars. No symbols, so no YAML/URL quoting surprises
# (REDIS_URL and DATABASE_URL embed these passwords).
gen() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 32; }

NC_RELEASE="${NC_RELEASE:-nextcloud}"

if [ -f "$ENV_FILE" ]; then
  echo "Reusing existing $ENV_FILE (delete it to generate new values)"
else
  # The Postgres *superuser* password was auto-generated by the chart and
  # never committed, so keep it. Changing it buys nothing and needs extra steps.
  PG_ADMIN=$(kubectl get secret -n nextcloud "${NC_RELEASE}-postgresql" \
             -o jsonpath='{.data.postgres-password}' 2>/dev/null | base64 -d || true)
  if [ -z "$PG_ADMIN" ]; then
    echo "WARN: couldn't read ${NC_RELEASE}-postgresql/postgres-password; generating one."
    echo "      You'll need to set it in Postgres too (see docs/SECRET-ROTATION.md)."
    PG_ADMIN=$(gen)
  fi
  umask 077
  cat > "$ENV_FILE" <<EOF
IMMICH_DB_PASSWORD=$(gen)
NC_ADMIN_PASSWORD=$(gen)
NC_DB_PASSWORD=$(gen)
NC_PG_ADMIN_PASSWORD=$PG_ADMIN
NC_REDIS_PASSWORD=$(gen)
EOF
  echo "Wrote new values to $ENV_FILE"
fi
# shellcheck disable=SC1090
source "$ENV_FILE"

seal() { kubeseal --controller-name "$SS_NAME" --controller-namespace "$SS_NS" -o yaml; }

kubectl create secret generic immich-postgres-secret -n immich \
  --type=kubernetes.io/basic-auth \
  --from-literal=username=immich \
  --from-literal=password="$IMMICH_DB_PASSWORD" \
  --dry-run=client -o yaml | seal > apps/immich/postgres-secret.yaml

kubectl create secret generic nextcloud-credentials -n nextcloud \
  --from-literal=nextcloud-username=admin \
  --from-literal=nextcloud-password="$NC_ADMIN_PASSWORD" \
  --from-literal=db-username=nextcloud \
  --from-literal=db-password="$NC_DB_PASSWORD" \
  --from-literal=postgres-password="$NC_PG_ADMIN_PASSWORD" \
  --from-literal=redis-password="$NC_REDIS_PASSWORD" \
  --dry-run=client -o yaml | seal > apps/nextcloud/sealed-secret.yaml

echo "Sealed: apps/immich/postgres-secret.yaml, apps/nextcloud/sealed-secret.yaml"
echo "Next: follow docs/SECRET-ROTATION.md step 2. Don't apply these yet."
